import { CHANGELOG_AUTHOR_UID } from './changelogAuthor';

const DIRECTOR_NAME = 'Markeith White';
const DIRECTOR_TITLE = 'TheSacramentoFree Director';

type FeatureSpec = {
  id: string;
  date: string;
  title: string;
  body: string;
  bullets?: string[];
  /** ISO timestamp — later same-day times sort first in the Updates tab. */
  at?: string;
};

function feature(spec: FeatureSpec) {
  const createdAt = spec.at ?? `${spec.date}T12:00:00.000Z`;
  const bulletBlock = spec.bullets?.length
    ? `\n\n${spec.bullets.map((line) => `• ${line}`).join('\n')}`
    : '';
  return {
    id: spec.id,
    date: spec.date,
    title: spec.title,
    body: spec.body,
    detail: `WHAT NEIGHBORS SEE
${spec.body}${bulletBlock}

— Mark`,
    directorName: DIRECTOR_NAME,
    directorTitle: DIRECTOR_TITLE,
    postedByUserId: CHANGELOG_AUTHOR_UID,
    createdAt,
    updatedAt: createdAt,
  };
}

